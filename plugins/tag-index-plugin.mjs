/**
 * Docusaurus plugin: 为 ai-docs (知识库) 生成一份「标签索引」数据文件。
 *
 * 为什么需要它:
 *   1. 中文分组。Docusaurus 内置的 `listTagsByLetters` 用 `label[0]` 分组,
 *      中文标签全按第一个汉字塞在一起; 我们改用拼音首字母 (见 src/utils/tags/pinyin.ts),
 *      但分组需要标签的全集, 页面的 props 里只有标签本身, 拿不到"每个标签有几篇",
 *      所以在构建期把索引算好。
 *   2. 详情页需要正文里没有的信息: 创建日期 (frontmatter created_at / git 首次提交),
 *      每篇的其它 tag (用于"换乘"), 以及标签的人工描述 (`ai-docs/.hx-tags.toml`)。
 *
 * 产物写进 data/ 目录 (和 docs-rss-plugin 写 data/latestDocs.ts 是同一套路),
 * 页面通过 `@site/data/aiDocTags` import, 构建期即可用, 无需运行时 fetch。
 * 数据 100% 可由内容目录重建, 不含任何状态。
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import matter from 'gray-matter';
// 直接复用 lodash 的实现: Docusaurus 的标签 permalink 就是 kebabCase(label),
// 自己手写容易在 HXLibs -> hx-libs / OAuth -> o-auth 这类边界上跑偏。
import kebabCase from 'lodash/kebabCase.js';

const GENERATED_HEADER = '// Auto-generated by tag-index-plugin — do not edit manually.';

function toPosix(p) {
  return p.replace(/\\/g, '/');
}

/** 去掉路径段前缀数字, 与 Docusaurus DefaultNumberPrefixParser 保持一致 */
function stripNumberPrefix(segment) {
  return segment.replace(/^\d+\s*[-_.]+\s*/, '');
}

/** git 首次提交时间 (ISO); 不在 git 仓库或文件未提交时返回 null */
function getGitCreatedAt(filePath, repoRoot) {
  try {
    const out = execFileSync(
      'git',
      ['log', '--diff-filter=A', '--follow', '--format=%aI', '--', filePath],
      { cwd: repoRoot, encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] },
    ).trim();
    if (!out) return null;
    const lines = out.split('\n').filter(Boolean);
    return lines[lines.length - 1];
  } catch {
    return null;
  }
}

function getFsModifiedAt(filePath) {
  try {
    return fs.statSync(filePath).mtime.toISOString();
  } catch {
    return new Date().toISOString();
  }
}

/** frontmatter 里的日期归一成 YYYY-MM-DD; 无法识别返回 null */
function normalizeDate(value) {
  if (value === null || value === undefined) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  const text = String(value).trim();
  const match = text.match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})/);
  if (match) {
    const [, y, m, d] = match;
    return `${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
  }
  const parsed = new Date(text);
  return Number.isNaN(parsed.getTime()) ? null : parsed.toISOString().slice(0, 10);
}

/** 正文剥掉 frontmatter/代码/语法后作为兜底摘要 */
function deriveDescription(content) {
  return content
    .replace(/^---[\s\S]*?---/, '')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/^#\s+.+$/gm, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[#*>`\-\[\]()|!~{}]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 160);
}

/**
 * 极简 TOML 读取: 只认 `[tags."名"]` 段落里的 `desc` 与 `aliases`。
 * 注册表是人手维护的固定格式, 不值得为此引入 TOML 依赖。
 */
function readTagRegistry(tagsFile) {
  const registry = new Map();
  if (!fs.existsSync(tagsFile)) return registry;

  let current = null;
  for (const rawLine of fs.readFileSync(tagsFile, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const header = line.match(/^\[tags\."(.+?)"\]\s*(?:#.*)?$/);
    if (header) {
      current = header[1];
      if (!registry.has(current)) registry.set(current, { desc: '', aliases: [] });
      continue;
    }
    if (line.startsWith('[')) {
      current = null;
      continue;
    }
    if (!current) continue;

    const desc = line.match(/^desc\s*=\s*"(.*)"$/);
    if (desc) {
      registry.get(current).desc = desc[1].trim();
      continue;
    }
    const aliases = line.match(/^aliases\s*=\s*\[(.*)\]$/);
    if (aliases) {
      registry.get(current).aliases = aliases[1]
        .split(',')
        .map((item) => item.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean);
    }
  }

  return registry;
}

/**
 * 复刻 Docusaurus 的 doc slug 规则 (plugin-content-docs getSlug):
 *   - 目录段去掉数字前缀;
 *   - 文件名是 index / readme 时, slug 就是所在目录 (即丢掉这一段);
 *   - frontmatter.slug 优先。
 */
function computeSlug({ relFile, frontMatterSlug, stripDirPrefixes = true }) {
  const withoutExt = relFile.replace(/\.mdx?$/i, '');
  const segments = withoutExt.split('/');
  const baseID = stripNumberPrefix(segments[segments.length - 1]);
  const dirSegments = segments.slice(0, -1);

  if (typeof frontMatterSlug === 'string' && frontMatterSlug.trim()) {
    return frontMatterSlug.trim().replace(/^\/+|\/+$/g, '');
  }

  const dirs = dirSegments.map((seg) => (stripDirPrefixes ? stripNumberPrefix(seg) : seg));
  const isIndexLike = baseID === 'index' || baseID === 'readme';
  const parts = isIndexLike ? dirs : [...dirs, baseID];
  return parts.join('/');
}

export default function tagIndexPlugin(_context, options) {
  const contentDir = options.contentDir ?? 'ai-docs';
  const routeBasePath = options.routeBasePath ?? 'knowledge-base';
  const outputFile = options.outputFile ?? 'data/aiDocTags.ts';
  const tagsFile = options.tagsFile ?? path.join(contentDir, '.hx-tags.toml');

  return {
    name: 'tag-index-plugin',

    async loadContent() {
      const siteDir = process.cwd();
      const absoluteContentDir = path.resolve(siteDir, contentDir);
      if (!fs.existsSync(absoluteContentDir)) return { tags: [], docs: [] };

      const registry = readTagRegistry(path.resolve(siteDir, tagsFile));
      const docs = [];

      function collect(dir) {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
          if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
          const full = path.join(dir, entry.name);
          if (entry.isDirectory()) {
            collect(full);
            continue;
          }
          if (!/\.mdx?$/i.test(entry.name)) continue;

          const raw = fs.readFileSync(full, 'utf8');
          const { data: frontMatter, content } = matter(raw);
          if (frontMatter.draft || frontMatter.unlisted || frontMatter.hx_protected) continue;

          const relFile = toPosix(path.relative(absoluteContentDir, full));
          const slug = computeSlug({ relFile, frontMatterSlug: frontMatter.slug });
          const title =
            frontMatter.sidebar_label ||
            frontMatter.title ||
            (content.match(/^#\s+(.+)$/m)?.[1] ?? '').trim() ||
            path.basename(path.dirname(full));

          const tags = Array.isArray(frontMatter.tags)
            ? frontMatter.tags
                .filter((tag) => typeof tag === 'string' && tag.trim())
                .map((tag) => tag.trim())
            : [];

          const date =
            normalizeDate(frontMatter.created_at) ||
            normalizeDate(frontMatter.date) ||
            (getGitCreatedAt(full, siteDir) ?? getFsModifiedAt(full)).slice(0, 10);

          docs.push({
            id: slug,
            title: String(title).trim(),
            description: String(frontMatter.description ?? '').trim() || deriveDescription(content),
            // 一律带前导 '/' 但**不带 baseUrl**: <Link to> 只对以 '/' 开头的路径补 baseUrl,
            // 少了这个斜杠会被 React Router 当成相对路径, 在 /tags/xxx 页面上二次拼接。
            permalink: `/${routeBasePath}/${slug}`,
            date,
            tags,
          });
        }
      }

      collect(absoluteContentDir);

      const counter = new Map();
      for (const doc of docs) {
        for (const tag of doc.tags) counter.set(tag, (counter.get(tag) ?? 0) + 1);
      }

      const tags = [...counter.entries()].map(([label, count]) => {
        const meta = registry.get(label);
        return {
          label,
          slug: kebabCase(label),
          permalink: `/${routeBasePath}/tags/${kebabCase(label)}`,
          count,
          description: meta?.desc ?? '',
          aliases: meta?.aliases ?? [],
        };
      });

      docs.sort((a, b) => (a.date === b.date ? a.id.localeCompare(b.id) : a.date < b.date ? 1 : -1));
      tags.sort((a, b) => b.count - a.count || a.label.localeCompare(b.label));

      const index = { tags, docs };
      // 在 loadContent 阶段就落盘, 让 `docusaurus start` (dev) 也能拿到数据 ——
      // postBuild 只在正式构建时跑, dev 下不会执行。
      writeDataModule(path.resolve(siteDir, outputFile), index, outputFile);

      return index;
    },
  };
}

function writeDataModule(target, content, outputFile) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, renderModule(content), 'utf8');
  console.log(`[tag-index] ${content.tags.length} tags / ${content.docs.length} docs -> ${outputFile}`);
}

function renderModule(content) {
  return `${GENERATED_HEADER}
export interface AiDocTagInfo {
  /** 标签原文 (frontmatter 里的写法) */
  label: string;
  /** 与内容插件一致的 slug (lodash.kebabCase) */
  slug: string;
  /** 标签详情页的站内路径 (不含 baseUrl) */
  permalink: string;
  /** 打这个标签的笔记数 */
  count: number;
  /** 注册表 ai-docs/.hx-tags.toml 里的人工描述, 可为空 */
  description: string;
  /** 注册表里登记的同义写法 */
  aliases: string[];
}

export interface AiDocEntry {
  /** 文档 slug (与内容插件保持一致, 目录数字前缀已去掉) */
  id: string;
  title: string;
  description: string;
  /** 站内路径 (不含 baseUrl) */
  permalink: string;
  /** YYYY-MM-DD */
  date: string;
  /** 这篇笔记的标签原文 */
  tags: string[];
}

export interface AiDocTagIndex {
  tags: AiDocTagInfo[];
  docs: AiDocEntry[];
  generatedAt: string;
}

export const aiDocTagIndex: AiDocTagIndex = ${JSON.stringify(
    { ...content, generatedAt: new Date().toISOString() },
    null,
    2,
  )};
`;
}
