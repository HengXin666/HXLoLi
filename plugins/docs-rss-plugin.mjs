/**
 * Docusaurus plugin: generates RSS/Atom feeds for docs (笔记).
 *
 * Mirrors the built-in blog plugin's feed generation, but for the docs
 * plugin which does not natively support RSS.  Integrates into the
 * Docusaurus lifecycle so feeds are generated during every build without
 * an external script.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import matter from 'gray-matter';
import { Feed } from 'feed';

/** @param {string} filePath */
function getGitDate(filePath) {
  try {
    const date = execSync(
      `git log -1 --format=%aI -- "${filePath}"`,
      { cwd: process.cwd(), encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'] }
    ).trim();
    return date || null;
  } catch {
    return null;
  }
}

/** @param {string} filePath */
function getFsDate(filePath) {
  try {
    return fs.statSync(filePath).mtime.toISOString();
  } catch {
    return new Date().toISOString();
  }
}

/**
 * @param {string} filePath  absolute path to the doc markdown file
 * @param {string} content   file contents
 * @param {string} docsDir   absolute path to the docs/ directory
 */
/** 模仿 Docusaurus DefaultNumberPrefixParser: 去掉路径段的前缀数字 */
function stripNumberPrefix(segment) {
  return segment.replace(/^\d+\s*[-_.]+\s*/, '');
}

function parseDocMeta(filePath, content, docsDir) {
  const { data: frontmatter } = matter(content);

  let title = frontmatter.sidebar_label || frontmatter.title || null;
  if (!title) {
    const match = content.match(/^#\s+(.+)$/m);
    if (match) title = match[1].trim();
  }
  if (!title) {
    title = path.basename(path.dirname(filePath));
  }

  let description = frontmatter.description || '';
  if (!description) {
    const text = content
      .replace(/^---[\s\S]*?---/, '')
      .replace(/^#\s+.+/gm, '')
      .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
      .replace(/[#*>`\-\[\]()|!~{}:]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    description = text.slice(0, 200) + (text.length > 200 ? '...' : '');
  }

  const rawDate = frontmatter.date || getGitDate(filePath) || getFsDate(filePath);
  // YAML 里的 date: 2026-10-01 会被 gray-matter 解析成 Date, 统一成 ISO 字符串
  const date = rawDate instanceof Date ? rawDate.toISOString() : String(rawDate);

  const rel = path.relative(docsDir, filePath).replace(/\\/g, '/');
  // 去掉扩展名和 /index, 然后对每段路径去掉数字前缀, 匹配 Docusaurus 默认 URL
  const slug = rel
    .replace(/(\/index)?\.mdx?$/, '')
    .split('/')
    .map(stripNumberPrefix)
    .join('/');

  let category = '笔记';
  const parts = rel.split('/');
  if (parts.length > 1) {
    const catMatch = parts[0].match(/^\d{3}-(.+)/);
    category = catMatch ? catMatch[1] : parts[0];
  }

  return { title, description, date, slug, category };
}

/** @param {string} docsDir */
function collectDocs(docsDir) {
  const results = [];

  /** @param {string} dir */
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
        walk(full);
      } else if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) {
        const content = fs.readFileSync(full, 'utf8');
        const { data: fm } = matter(content);
        if (fm.draft || fm.unlisted || fm.hx_protected) continue;
        results.push(parseDocMeta(full, content, docsDir));
      }
    }
  }

  walk(docsDir);
  return results;
}

/** 首页每栏条数 */
const LATEST_COUNT = 6;

/** @param {{title:string,slug:string,date:string,category:string,description:string}} d */
function toLatest(d) {
  return {
    title: d.title,
    to: `/docs/${d.slug}`,
    date: d.date.slice(0, 10),
    category: d.category,
    description: d.description.slice(0, 100),
  };
}

const LATEST_FILE = () => path.resolve(process.cwd(), 'data', 'latestDocs.ts');

/** 读出上一次生成的博客 / ai-docs 两栏, 读不到就是空数组 */
function readPrevious() {
  const pick = (text, name) => {
    const m = text.match(new RegExp(`export const ${name}: LatestDoc\\[\\] = (\\[[\\s\\S]*?\\]);\\n`));
    try { return m ? JSON.parse(m[1]) : []; } catch { return []; }
  };
  try {
    const text = fs.readFileSync(LATEST_FILE(), 'utf8');
    return { blogs: pick(text, 'latestBlogs'), aiDocs: pick(text, 'latestAiDocs') };
  } catch {
    return { blogs: [], aiDocs: [] };
  }
}

/** 写 data/latestDocs.ts: 笔记 (docs/) / 博客 (blog/) / AI 文章 (ai-docs/) 三个数组, 内容不变时不落盘 */
function writeLatest({ docs, blogs, aiDocs }) {
  const text = `// Auto-generated by docs-rss-plugin — do not edit manually.
export interface LatestDoc {
  title: string;
  to: string;
  date: string;
  category: string;
  description: string;
}

/** docs/ 下最近更新的笔记 */
export const latestDocs: LatestDoc[] = ${JSON.stringify(docs, null, 2)};

/** blog/ 下最近的博客 */
export const latestBlogs: LatestDoc[] = ${JSON.stringify(blogs, null, 2)};

/** ai-docs/ (路由 /knowledge-base) 下最近的 AI 文章 */
export const latestAiDocs: LatestDoc[] = ${JSON.stringify(aiDocs, null, 2)};
`;
  const file = LATEST_FILE();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  let before = null;
  try { before = fs.readFileSync(file, 'utf8'); } catch { /* 首次生成 */ }
  if (before !== text) fs.writeFileSync(file, text, 'utf8');
}

/**
 * 生成 docs 的 RSS/Atom, 以及首页"最近更新"三栏的数据 data/latestDocs.ts (笔记 / 博客 / AI 文章).
 * .agents/notes/implemented/feature/2026-10-31-homepage-profile-and-project-index.md
 * @param {object} ctx Docusaurus context
 */
export default function docsRssPlugin(_context, _options) {
  return {
    name: 'docs-rss-plugin',

    async loadContent() {
      const docsDir = path.resolve(process.cwd(), 'docs');
      const docs = collectDocs(docsDir);
      docs.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

      // Write data/latestDocs.ts now so @site/data import resolves at compile time
      const latest = docs.slice(0, LATEST_COUNT).map(toLatest);
      // 先只写 docs 一栏, 博客与 ai-docs 两栏沿用文件里已有的值; allContentLoaded 再整份重写.
      // 这样即使别的插件加载失败, @site/data/latestDocs 也始终导出三个数组, 首页不会编译失败.
      const previous = readPrevious();
      writeLatest({ docs: latest, blogs: previous.blogs, aiDocs: previous.aiDocs });

      return docs;
    },

    /**
     * 首页"最近"拆成笔记 / 博客 / AI 文章三栏: 博客与 ai-docs 的 permalink、日期直接取各自插件加载好的元数据,
     * 不在这里重算 slug, 保证点进去的路径与站点路由一致.
     * 决策记录见文件里 docsRssPlugin 的注释
     */
    async allContentLoaded({ allContent, content: docs }) {
      const baseUrl = _context.baseUrl || '/';
      const local = (permalink) => '/' + permalink.slice(permalink.startsWith(baseUrl) ? baseUrl.length : 1);
      const hidden = (fm = {}, item = {}) => Boolean(fm.draft || fm.unlisted || fm.hx_protected || item.draft || item.unlisted);

      const blogContent = allContent['docusaurus-plugin-content-blog']?.default;
      const blogs = (blogContent?.blogPosts ?? [])
        .map((post) => post.metadata)
        .filter((meta) => !hidden(meta.frontMatter, meta))
        .map((meta) => ({
          title: meta.title,
          to: local(meta.permalink),
          date: new Date(meta.date).toISOString(),
          category: meta.tags?.[0]?.label ?? '博客',
          description: (meta.description ?? '').slice(0, 100),
        }))
        .sort((a, b) => b.date.localeCompare(a.date))
        .slice(0, LATEST_COUNT)
        .map((item) => ({ ...item, date: item.date.slice(0, 10) }));

      const aiContent = allContent['docusaurus-plugin-content-docs']?.['ai-docs'];
      const aiDocs = (aiContent?.loadedVersions?.[0]?.docs ?? [])
        .filter((doc) => !hidden(doc.frontMatter, doc))
        .map((doc) => {
          // ai-docs 的日期以 front matter 的 created_at 为准, 没有再退回最后更新时间
          const created = doc.frontMatter?.created_at;
          const date = created
            ? String(created instanceof Date ? created.toISOString() : created).slice(0, 10)
            : doc.lastUpdatedAt ? new Date(doc.lastUpdatedAt).toISOString().slice(0, 10) : '';
          const top = (doc.sourceDirName ?? '').split('/')[0];
          return {
            title: doc.title,
            to: local(doc.permalink),
            date,
            category: stripNumberPrefix(top) || 'AI 文章',
            description: (doc.description ?? '').slice(0, 100),
          };
        })
        .sort((a, b) => b.date.localeCompare(a.date) || b.to.localeCompare(a.to))
        .slice(0, LATEST_COUNT);

      const latest = (docs ?? []).slice(0, LATEST_COUNT).map(toLatest);
      writeLatest({ docs: latest, blogs, aiDocs });
    },

    async postBuild({ siteConfig, outDir, content: docs }) {
      const { url: siteUrl, baseUrl } = siteConfig;
      const docsBase = `${siteUrl}${baseUrl}docs`;

      // Sort by date desc
      docs.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

      const feed = new Feed({
        id: docsBase,
        title: 'HXLoLi 笔记',
        updated: docs.length > 0 ? new Date(docs[0].date) : new Date(),
        language: 'zh-Hans',
        link: docsBase,
        description: 'HXLoLi 最新笔记更新',
        favicon: `${siteUrl}${baseUrl}img/favicon.ico`,
        copyright: `© ${new Date().getFullYear()} HXLoLi`,
      });

      for (const doc of docs.slice(0, 20)) {
        feed.addItem({
          title: doc.title,
          id: `${docsBase}/${doc.slug}`,
          link: `${docsBase}/${doc.slug}`,
          date: new Date(doc.date),
          description: doc.description,
          category: [{ name: doc.category }],
        });
      }

      fs.writeFileSync(path.join(outDir, 'docs-rss.xml'), feed.rss2(), 'utf8');
      fs.writeFileSync(path.join(outDir, 'docs-atom.xml'), feed.atom1(), 'utf8');

      // Also copy to static so they're usable during dev
      const staticDir = path.resolve(process.cwd(), 'static');
      fs.mkdirSync(staticDir, { recursive: true });
      fs.writeFileSync(path.join(staticDir, 'docs-rss.xml'), feed.rss2(), 'utf8');
      fs.writeFileSync(path.join(staticDir, 'docs-atom.xml'), feed.atom1(), 'utf8');

      console.log(`[docs-rss] Generated feeds (${docs.length} entries)`);
    },
  };
}
