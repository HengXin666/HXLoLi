export const projectById: Record<string, EcosystemProject> = Object.fromEntries(
    projects.map((project) => [project.id, project]),
);

export type ProjectRelation = {
    otherId: string;
    kind: EdgeKind;
    inferred: boolean;
    evidence: string;
    /** out: 本项目指向对方. in: 对方指向本项目. */
    direction: "out" | "in";
};

/**
 * 某个项目在图上的全部邻边, 详情卡用它列出关系.
 */
export function relationsOf(id: string): ProjectRelation[] {
    const found: ProjectRelation[] = [];
    for (const edge of edges) {
        if (edge.from === id) {
            found.push({
                otherId: edge.to,
                kind: edge.kind,
                inferred: Boolean(edge.inferred),
                evidence: edge.evidence,
                direction: "out",
            });
        } else if (edge.to === id) {
            found.push({
                otherId: edge.from,
                kind: edge.kind,
                inferred: Boolean(edge.inferred),
                evidence: edge.evidence,
                direction: "in",
            });
        }
    }
    return found;
}

